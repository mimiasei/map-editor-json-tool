// ─── Story generator ───────────────────────────────────────────────────────────
// Turns a StoryDef + the user's slot bindings into plain scenario content:
// one quest per beat, chained with NextQuest; integer counters as story
// variables; dialog flows (with multi-answer choices); English text tokens from
// the offline phrase banks, plus a TextSpec per token for the text writer.

import i18n from '@/lib/i18n'
import { slotLabel } from './story-display'
import type { Quest, Counter, Trigger, Action, Condition, SubQuest } from '@/types/scenario'
import type { DialogFlow, DialogAnswer, DialogSlide } from '@/types/dialog'
import type {
  BeatDef,
  Consequence,
  GeneratedStory,
  StoryDef,
  StoryEnv,
  StoryInput,
  StoryVariable,
  TextKind,
  AnswerIntent,
} from '@/types/story'
import { EMPTY_GENERATED_STORY } from '@/types/story'
import { createSeededRng } from '@/lib/rmg/seeded-rng'
import { createStoryNamer, type ExistingStorySids } from './namer'
import { humanizeEntity } from './phrases'
import { offlineText } from './text'

const COMMENT = 'Generated by Story Builder (v1)'

// ─── Validation ────────────────────────────────────────────────────────────────

/** Problems with a story definition itself (author errors, not user errors). */
export function validateStoryDef(def: StoryDef): string[] {
  const errors: string[] = []
  const slotIds = new Set(def.slots.map((s) => s.id))
  const varKeys = new Set(def.variables.map((v) => v.key))
  const needSlot = (slot: string, beat: string) => {
    if (!slotIds.has(slot)) errors.push(`${beat}: unknown slot "${slot}".`)
  }
  const needVar = (key: string, beat: string) => {
    if (!varKeys.has(key)) errors.push(`${beat}: unknown variable "${key}".`)
  }
  def.beats.forEach((beat, i) => {
    const where = `Beat ${i + 1} (${beat.kind})`
    switch (beat.kind) {
      case 'visit':
        needSlot(beat.slot, where)
        needVar(beat.variable, where)
        break
      case 'capture':
      case 'defeat':
        needSlot(beat.slot, where)
        break
      case 'choice':
        needVar(beat.variable, where)
        if (beat.slot) needSlot(beat.slot, where)
        if (beat.answers.length < 2 || beat.answers.length > 4) errors.push(`${where}: needs 2-4 answers.`)
        for (const a of beat.answers)
          for (const c of a.consequences) if (c.kind === 'score') needVar(c.variable, where)
        break
      case 'finale': {
        if (beat.endings.length === 0) errors.push(`${where}: needs at least one ending.`)
        const last = beat.endings[beat.endings.length - 1]
        if (last && last.when) errors.push(`${where}: the last ending must be the fallback (no condition).`)
        for (const e of beat.endings) if (e.when) needVar(e.when.variable, where)
        break
      }
      default:
        break
    }
  })
  if (def.beats.length > 0 && def.beats[def.beats.length - 1].kind !== 'finale')
    errors.push('The last beat should be a finale.')
  return errors
}

/** What the user still has to bind before the story can be built. */
export function validateStoryInput(def: StoryDef, input: StoryInput): string[] {
  const errors: string[] = []
  for (const slot of def.slots) {
    const picks = (input.slots[slot.id] ?? []).filter(Boolean)
    if (picks.length < slot.min) {
      errors.push(
        slot.min === 1
          ? i18n.t('story.validation.pickOne', { what: slotLabel(slot).toLowerCase() })
          : i18n.t('story.validation.pickMin', { min: slot.min, what: slotLabel(slot).toLowerCase() }),
      )
    }
    if (slot.cardinality === 'one' && picks.length > 1) errors.push(i18n.t('story.validation.pickOnlyOne', { label: slotLabel(slot) }))
  }
  return errors
}

// ─── Generator ─────────────────────────────────────────────────────────────────

export function buildStory(
  def: StoryDef,
  input: StoryInput,
  env: StoryEnv,
  existing: ExistingStorySids,
): GeneratedStory {
  const out = EMPTY_GENERATED_STORY()
  const namer = createStoryNamer(env.mapName, def.id, existing)
  const rng = createSeededRng(input.seed)

  const nameOf = (sid: string) => env.entityNames[sid] || humanizeEntity(sid)
  const picks = (slot: string) => (input.slots[slot] ?? []).filter(Boolean)
  const firstPlace = (() => {
    for (const s of def.slots) {
      const p = picks(s.id)[0]
      if (p) return nameOf(p)
    }
    return 'the frontier'
  })()

  // Variables -> counters
  const varSid: Record<string, string> = {}
  for (const v of def.variables) {
    const sid = namer.counter(v.key)
    varSid[v.key] = sid
    const counter: Counter = { sid, value: 0, comment: `${COMMENT}: ${v.label}` }
    if (v.min !== undefined) counter.minValue = v.min
    if (v.max !== undefined) counter.maxValue = v.max
    out.counters.push(counter)
    const sv: StoryVariable = { sid, label: v.label, kind: v.kind, min: v.min, max: v.max }
    out.variables.push(sv)
  }

  const questSids = def.beats.map((b, i) => namer.quest(`q${i + 1}_${b.kind}`))

  /** Creates a text token with the offline English text and records its spec. */
  function text(
    kind: TextKind,
    owner: string,
    vals: Record<string, string>,
    opts: { intent?: AnswerIntent; speaker?: string } = {},
  ): string {
    const sid = namer.token(owner, kind)
    out.localizationTokens[sid] = offlineText({ kind, tone: input.tone, intent: opts.intent, context: vals }, rng)
    out.textSpecs.push({
      id: sid,
      kind,
      tone: input.tone,
      length: input.length,
      speaker: opts.speaker,
      intent: opts.intent,
      context: vals,
    })
    return sid
  }

  /** A one-slide dialog; returns its dialog sid. */
  function simpleDialog(
    owner: string,
    kind: TextKind,
    vals: Record<string, string>,
    extra: Partial<DialogSlide> = {},
  ): string {
    const dialogSid = namer.dialog(owner)
    const slide: DialogSlide = { id: 'start', text: text(kind, dialogSid, vals), end: true, ...extra }
    out.dialogFlows.push({ id: dialogSid, localization: true, slides: [slide] } as DialogFlow)
    return dialogSid
  }

  function consequenceActions(cs: Consequence[]): Action[] {
    const actions: Action[] = []
    for (const c of cs) {
      if (c.kind === 'score') {
        const sid = varSid[c.variable]
        actions.push({ a: c.amount >= 0 ? 'CounterPlus' : 'CounterMinus', p: [sid, String(Math.abs(c.amount))] })
      } else {
        actions.push({ a: c.amount >= 0 ? 'GiveRes' : 'RemoveRes', p: [c.resource, String(Math.abs(c.amount))] })
      }
    }
    return actions
  }

  const advance = (i: number): Action[] => [
    { a: 'CurrentSubQuestDone', p: [] },
    { a: 'NextQuest', p: i < def.beats.length - 1 ? [questSids[i + 1]] : [] },
  ]
  const now: Condition = { c: 'StartTurn', p: [] }

  function objectiveText(beat: BeatDef, place: string): string {
    switch (beat.kind) {
      case 'intro':
        return 'Begin your journey'
      case 'visit':
        return `Visit the marked places (${picks(beat.slot).length})`
      case 'capture':
        return `Capture ${place}`
      case 'defeat':
        return `Defeat the guards of ${place}`
      case 'resources':
        return `Gather ${beat.amount} ${beat.resource}`
      case 'timer':
        return `Survive ${beat.days} days`
      case 'reward':
        return 'Claim your reward'
      case 'choice':
        return 'Make your choice'
      case 'finale':
        return 'See the story to its end'
    }
  }

  function buildQuest(i: number, beat: BeatDef): Quest {
    const questSid = questSids[i]
    const baseVals: Record<string, string> = { place: firstPlace }
    const note = def.notes?.[i]
    if (note) baseVals.note = note
    const triggers: Trigger[] = []

    switch (beat.kind) {
      case 'intro': {
        const d = simpleDialog(`${i + 1}_intro`, 'intro', baseVals)
        triggers.push({ conditions: [now], actions: [{ a: 'Dialog', p: [d] }, ...advance(i)] })
        break
      }
      case 'visit': {
        const sites = picks(beat.slot)
        const counter = varSid[beat.variable]
        baseVals.n = String(sites.length)
        sites.forEach((site, k) => {
          const d = simpleDialog(`${i + 1}_clue_${k + 1}`, 'clue', { ...baseVals, place: nameOf(site) })
          triggers.push({
            conditions: [{ c: 'ObjectInteractionBefore', p: [site, ''] }],
            actions: [{ a: 'CounterPlus', p: [counter, '1'] }, { a: 'Dialog', p: [d] }],
          })
        })
        triggers.push({
          conditions: [{ c: 'Counter', p: [counter, '>=', String(sites.length)] }],
          actions: advance(i),
        })
        break
      }
      case 'capture':
      case 'defeat': {
        const target = picks(beat.slot)[0]
        baseVals.place = nameOf(target)
        const d = simpleDialog(`${i + 1}_${beat.kind}`, 'clue', baseVals)
        const cond: Condition =
          beat.kind === 'capture'
            ? { c: 'ObjectCaptureEntity', p: [target] }
            : { c: 'SquadKill', p: [target, ''] }
        triggers.push({ conditions: [cond], actions: [{ a: 'Dialog', p: [d] }, ...advance(i)] })
        break
      }
      case 'resources': {
        const d = simpleDialog(`${i + 1}_resources`, 'clue', baseVals)
        triggers.push({
          conditions: [{ c: 'ResCounter', p: [beat.resource, '>=', String(beat.amount)] }],
          actions: [{ a: 'Dialog', p: [d] }, ...advance(i)],
        })
        break
      }
      case 'timer': {
        const d = simpleDialog(`${i + 1}_timer`, 'clue', baseVals)
        triggers.push({
          conditions: [{ c: 'StartTurn', p: [], counter: beat.days }],
          actions: [{ a: 'Dialog', p: [d] }, ...advance(i)],
        })
        break
      }
      case 'reward': {
        const d = simpleDialog(`${i + 1}_reward`, 'reward', baseVals)
        triggers.push({
          conditions: [now],
          actions: [
            { a: 'GiveRes', p: [beat.resource, String(beat.amount)] },
            { a: 'Dialog', p: [d] },
            ...advance(i),
          ],
        })
        break
      }
      case 'choice': {
        const counter = varSid[beat.variable]
        const dialogSid = namer.dialog(`${i + 1}_choice`)
        const answers: DialogAnswer[] = []
        const slides: DialogSlide[] = []
        beat.answers.forEach((a, k) => {
          const answer: DialogAnswer = {
            text: text('answer', `${dialogSid}_a${k + 1}`, baseVals, { intent: a.intent }),
            actions: [{ a: 'Go', p: [`out_${k + 1}`] }],
            mapActions: [{ a: 'CounterSet', p: [counter, String(k + 1)] }, ...consequenceActions(a.consequences)],
          }
          if (a.requiresGold) {
            answer.requests = [{ c: 'ResCounter', p: ['gold', '>=', String(a.requiresGold)] }]
          }
          answers.push(answer)
          slides.push({
            id: `out_${k + 1}`,
            text: text('outcome', `${dialogSid}_o${k + 1}`, baseVals, { intent: a.intent }),
            end: true,
          })
        })
        out.dialogFlows.push({
          id: dialogSid,
          localization: true,
          slides: [{ id: 'start', text: text('choice_prompt', dialogSid, baseVals), answers }, ...slides],
        } as DialogFlow)
        const slotTarget = beat.slot ? picks(beat.slot)[0] : undefined
        triggers.push({
          conditions: [slotTarget ? { c: 'ObjectInteractionBefore', p: [slotTarget, ''] } : now],
          actions: [{ a: 'Dialog', p: [dialogSid] }],
        })
        triggers.push({
          conditions: [{ c: 'Counter', p: [counter, '>=', '1'] }],
          actions: advance(i),
        })
        break
      }
      case 'finale': {
        const actions: Action[] = [{ a: 'CurrentSubQuestDone', p: [] }]
        beat.endings.forEach((ending, k) => {
          const extra: Partial<DialogSlide> = beat.victory
            ? { closeMapActions: [{ a: 'GameVictory', p: [] }] }
            : {}
          const d = simpleDialog(`${i + 1}_ending_${k + 1}`, 'finale', baseVals, extra)
          if (ending.when) {
            const w = ending.when
            actions.push({ a: 'DialogIfCounter', p: [d, varSid[w.variable], w.op, String(w.value), 'break'] })
          } else {
            actions.push({ a: 'Dialog', p: [d] })
          }
        })
        triggers.push({ conditions: [now], actions })
        break
      }
    }

    // The quest log lists every sub-quest by name; without one the game shows "NULL".
    // Objectives are short fixed English lines (not written by the text service).
    const objectiveSid = namer.token(questSid, 'objective')
    out.localizationTokens[objectiveSid] = objectiveText(beat, baseVals.place)
    const subQuest: SubQuest = { sid: '1', name: objectiveSid, activeOnStart: true, comment: COMMENT, triggers }
    return {
      sid: questSid,
      name: text('quest_name', questSid, baseVals),
      desc: text('quest_desc', questSid, baseVals),
      activeOnStart: i === 0,
      sharing: 'Clone',
      comment: COMMENT,
      subQuests: [subQuest],
    }
  }

  def.beats.forEach((beat, i) => out.quests.push(buildQuest(i, beat)))
  return out
}
