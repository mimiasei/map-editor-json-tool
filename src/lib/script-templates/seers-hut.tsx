// ─── Script Template: Seer's Hut (issue #149) ─────────────────────────────────
// Real HoMM3 mechanic (verified via web research: heroes.thelazy.net,
// mightandmagic.fandom.com, and community discussion of the exact quest/reward
// vocabulary added in Armageddon's Blade): a hero visits the Seer's Hut and is
// offered a quest. Returning once the requirement is met grants a reward; for
// "bring X" style requirements (resources, artifacts) the brought items are
// CONSUMED as payment — level/skill/kill-based requirements consume nothing.
// The quest completes once, for whichever player's hero fulfills it first.
//
// This app's condition vocabulary models "requirement met" as a persistent,
// re-checkable state (ResCounter/ItemOwnSide/etc. — see CONDITION_REGISTRY),
// not a one-off event, so AND-combining the hut-visit condition with the
// requirement condition in one trigger correctly expresses "hero walks in
// AFTER already meeting the requirement" — matching real Seer's Hut behavior
// (you must physically return to collect; satisfying the condition remotely
// doesn't auto-grant the reward). See src/schema/conditions.ts/actions.ts for
// the exact building blocks reused here.
//
// Scope decisions, made after checking exactly what this engine's vocabulary
// supports (not guessed — see the exploration that produced this file):
// - Requirement types offered: Resources, Artifact, Defeat Monster, Defeat
//   Hero, Primary Skill. "Hero level >= N" is NOT offered — there is no
//   native level-check condition anywhere in this engine's vocabulary (only
//   TutorialLevelUp, a one-shot trip-wire with no threshold), so it can't be
//   built without inventing behavior that doesn't exist.
// - "Bring Creatures" is NOT offered as a requirement type: the only
//   ownership check scoped to a single hero (UnitOwnHero) requires a fixed,
//   explicit Hero SID with no "any/currently-interacting hero" option (unlike
//   ObjectInteractionAfter's hero param, HeroStat's hero param, or
//   GiveItemHero/GiveStatsHero's hero param, which all support leaving the
//   hero blank to mean "whichever hero is involved"). Offering it would mean
//   either silently restricting the quest to one named hero (surprising) or
//   producing a condition that can never fire for other heroes.
// - Reward types offered: Resources, Artifact, Primary Skill boost. Give
//   Experience is NOT offered for the same reason — GiveExpHero's Hero SID
//   param is required, not blank-able, so it can't target "whichever hero
//   turned in the quest" generically.
// - No "hint message on an incomplete visit" — Dialog actions only ever
//   reference an existing DialogFlow by sid (there's no inline-text variant),
//   so an optional "offer" dialog on first visit is supported (user picks an
//   existing dialog sid, authored separately in the Dialog Editor), but a
//   dynamic "you haven't met the requirement yet" hint is out of scope — it
//   would require negating a condition, which this engine's trigger model
//   (AND/OR over a flat condition list) doesn't expose.

