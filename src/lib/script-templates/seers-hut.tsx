// ─── Validate ───────────────────────────────────────────────────────────────

function validate(input: ScriptTemplateInput): string[] {
  const errors: string[] = []
  const hutSid = field(input, 'hutSid').trim()
  const requirementType = (field(input, 'requirementType') || 'resources') as RequirementType
  const rewardType = (field(input, 'rewardType') || 'resources') as RewardType

  if (!hutSid) errors.push("Pick the object acting as the Seer's Hut.")

  switch (requirementType) {
    case 'resources':
      if (!(Number(field(input, 'reqResourceAmount')) > 0)) errors.push('Set a positive required resource amount.')
      break
    case 'artifact':
      if (!field(input, 'reqArtifactSid').trim()) errors.push('Pick the artifact the hero must bring.')
      break
    case 'defeatMonster':
      if (!field(input, 'reqSquadSid').trim()) errors.push('Pick the neutral squad that must be defeated.')
      break
    case 'defeatHero':
      if (!field(input, 'reqHeroSid').trim()) errors.push('Pick the hero that must be defeated.')
      break
    case 'skill':
      if (!(Number(field(input, 'reqSkillAmount')) > 0)) errors.push('Set a positive required skill level.')
      break
  }

  switch (rewardType) {
    case 'resources':
      if (!(Number(field(input, 'rewardResourceAmount')) > 0)) errors.push('Set a positive reward resource amount.')
      break
    case 'artifact':
      if (!field(input, 'rewardArtifactSid').trim()) errors.push('Pick the artifact reward.')
      break
    case 'skill':
      if (!(Number(field(input, 'rewardSkillAmount')) > 0)) errors.push('Set a positive reward skill amount.')
      break
  }

  return errors
}

// ─── Generate ───────────────────────────────────────────────────────────────

function generate(input: ScriptTemplateInput, existingSids: { quests: string[] }) {
  const hutSid = field(input, 'hutSid').trim()
  const requirementType = (field(input, 'requirementType') || 'resources') as RequirementType
  const rewardType = (field(input, 'rewardType') || 'resources') as RewardType

  let requirementCondition: Condition
  const consumeActions: Action[] = []

  switch (requirementType) {
    case 'resources': {
      const resource = field(input, 'reqResourceId') || 'gold'
      const amount = String(Number(field(input, 'reqResourceAmount')) || 0)
      requirementCondition = { c: 'ResCounter', p: [resource, '>=', amount] }
      consumeActions.push({ a: 'RemoveRes', p: [resource, amount] })
      break
    }
    case 'artifact': {
      const artifactSid = field(input, 'reqArtifactSid').trim()
      requirementCondition = { c: 'ItemOwnSide', p: [artifactSid, '>=', '1'] }
      consumeActions.push({ a: 'RemoveItem', p: [artifactSid] })
      break
    }
    case 'defeatMonster':
      requirementCondition = { c: 'SquadKill', p: [field(input, 'reqSquadSid').trim(), ''] }
      break
    case 'defeatHero':
      requirementCondition = { c: 'HeroKill', p: [field(input, 'reqHeroSid').trim()] }
      break
    case 'skill': {
      const skill = field(input, 'reqSkill') || 'offence'
      const amount = String(Number(field(input, 'reqSkillAmount')) || 0)
      // Blank hero SID = whichever hero is currently involved, matching
      // ObjectInteractionAfter's own "leave blank for any hero" convention.
      requirementCondition = { c: 'HeroStat', p: ['', skill, '>=', amount] }
      break
    }
  }

  let rewardAction: Action
  switch (rewardType) {
    case 'resources': {
      const resource = field(input, 'rewardResourceId') || 'gold'
      const amount = String(Number(field(input, 'rewardResourceAmount')) || 0)
      rewardAction = { a: 'GiveRes', p: [resource, amount] }
      break
    }
    case 'artifact':
      rewardAction = { a: 'GiveItemHero', p: [field(input, 'rewardArtifactSid').trim(), ''] }
      break
    case 'skill': {
      const skill = field(input, 'rewardSkill') || 'offence'
      const amount = String(Number(field(input, 'rewardSkillAmount')) || 0)
      rewardAction = { a: 'GiveStatsHero', p: [skill, '', amount] }
      break
    }
  }

  const triggers: Trigger[] = []

  const offerDialogSid = field(input, 'offerDialogSid').trim()
  if (offerDialogSid) {
    triggers.push({
      conditions: [{ c: 'ObjectInteractionAfter', p: [hutSid, ''] }],
      actions: [{ a: 'Dialog', p: [offerDialogSid] }],
    })
  }

  const rewardDialogSid = field(input, 'rewardDialogSid').trim()
  triggers.push({
    conditionsLogic: 'And',
    conditions: [{ c: 'ObjectInteractionAfter', p: [hutSid, ''] }, requirementCondition],
    actions: [
      ...consumeActions,
      rewardAction,
      ...(rewardDialogSid ? [{ a: 'Dialog', p: [rewardDialogSid] } as Action] : []),
    ],
  })

  const subQuest: SubQuest = {
    sid: '1',
    activeOnStart: true,
    comment: GENERATED_COMMENT,
    triggers,
  }

  const sid = existingSids.quests.includes(BASE_QUEST_SID)
    ? uniqueSid(BASE_QUEST_SID, existingSids.quests)
    : BASE_QUEST_SID

  const quest: Quest = {
    sid,
    hidden: true,
    activeOnStart: true,
    comment: GENERATED_COMMENT,
    subQuests: [subQuest],
  }

  return { quest }
}

