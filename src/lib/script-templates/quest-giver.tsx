// ─── Script Template: Quest Giver (generated text) ────────────────────────────
// Same mechanic as the Seer's Hut template (a hero visits an object; once the
// requirement is met on a later visit the reward is granted), but the quest log
// name/description and the intro + success dialogs are written for you from a
// tone and a seed. Same seed = same text; Re-roll picks a new seed.
//
// The requirement/reward vocabulary and its engine limits are shared with
// seers-hut.tsx (see the header there). Not offered: a "not done yet" reminder
// dialog, because the trigger model cannot negate a condition.

import { Fragment } from 'react'
import type { Quest, SubQuest, Trigger, Action } from '@/types/scenario'
import type { DialogFlow } from '@/types/dialog'
import type { ScriptTemplateDef, ScriptTemplateInput, ScriptTemplateFieldsProps } from '@/types/script-template'
import { uniqueSid } from '@/store/useScenarioStore'
import { Input } from '@/components/ui/input'
import { Button } from '@/components/ui/button'
import { RefreshCw } from '@/components/ui/icons'
import MapEntityPickField from '@/components/common/MapEntityPickField'
import {
  Field,
  EnumSelect,
  RequirementFields,
  RewardFields,
  REQUIREMENT_OPTIONS,
  REWARD_OPTIONS,
  PRIMARY_SKILL_LABELS,
  buildRequirement,
  buildReward,
  field,
  setField,
  validateRequirementAndReward,
  type RequirementType,
  type RewardType,
} from './seers-hut'
import { TONES, toneLabel, type Tone } from './text-gen/phrases'
import { generateQuestText, humanizeSid, type QuestTextParts } from './text-gen/generate-text'
import i18n from '@/lib/i18n'

const GENERATED_COMMENT = 'Generated by Script Template: Quest Giver (v1)'
const BASE_QUEST_SID = 'script_quest_giver'

function toneOf(input: ScriptTemplateInput): Tone {
  const t = field(input, 'tone')
  return (TONES as readonly string[]).includes(t) ? (t as Tone) : 'heroic'
}

function seedOf(input: ScriptTemplateInput): number {
  const n = Number(field(input, 'seed'))
  return Number.isFinite(n) && n > 0 ? Math.floor(n) : 1
}

/** Plain-language task / reward / giver phrases for the text grammar. */
export function describeParts(input: ScriptTemplateInput): QuestTextParts {
  const requirementType = (field(input, 'requirementType') || 'resources') as RequirementType
  const rewardType = (field(input, 'rewardType') || 'resources') as RewardType

  let task: string
  switch (requirementType) {
    case 'resources':
      task = `Bring ${Number(field(input, 'reqResourceAmount')) || 0} ${field(input, 'reqResourceId') || 'gold'}`
      break
    case 'artifact':
      task = `Bring me the ${humanizeSid(field(input, 'reqArtifactSid')) || 'artifact'}`
      break
    case 'defeatMonster':
      task = 'Destroy the monsters that plague this land'
      break
    case 'defeatHero':
      task = `Defeat ${humanizeSid(field(input, 'reqHeroSid')) || 'the enemy hero'}`
      break
    case 'skill': {
      const skill = field(input, 'reqSkill') || 'offence'
      task = `Grow your ${PRIMARY_SKILL_LABELS[skill] ?? skill} to ${Number(field(input, 'reqSkillAmount')) || 0}`
      break
    }
  }

  let reward: string
  switch (rewardType) {
    case 'resources':
      reward = `${Number(field(input, 'rewardResourceAmount')) || 0} ${field(input, 'rewardResourceId') || 'gold'}`
      break
    case 'artifact':
      reward = `the ${humanizeSid(field(input, 'rewardArtifactSid')) || 'artifact'}`
      break
    case 'skill': {
      const skill = field(input, 'rewardSkill') || 'offence'
      reward = `${Number(field(input, 'rewardSkillAmount')) || 0} points of ${PRIMARY_SKILL_LABELS[skill] ?? skill}`
      break
    }
  }

  return { giver: field(input, 'giverName').trim() || 'The quest giver', task, reward }
}

function renderFields(props: ScriptTemplateFieldsProps) {
  const { input, setInput } = props
  const requirementType = (field(input, 'requirementType') || 'resources') as RequirementType
  const rewardType = (field(input, 'rewardType') || 'resources') as RewardType
  const text = generateQuestText(toneOf(input), describeParts(input), seedOf(input))

  return (
    <Fragment>
      <Field label={i18n.t('tree.scriptTemplateForms.questGiver.questGiverObject')}>
        <MapEntityPickField
          value={field(input, 'giverSid')}
          onChange={(v) => setField(setInput, 'giverSid', v)}
          placeholder={i18n.t('tree.scriptTemplateDialog.searchPlacedObjects')}
          label={i18n.t('tree.scriptTemplateForms.questGiver.questGiverObject')}
          requestMapPick={props.requestMapPick}
        />
      </Field>
      <Field label={i18n.t('tree.scriptTemplateForms.questGiver.questGiverNameUsedIn')}>
        <Input
          value={field(input, 'giverName')}
          onChange={(e) => setField(setInput, 'giverName', e.target.value)}
          placeholder={i18n.t('tree.scriptTemplateForms.questGiver.eGTheHermit')}
        />
      </Field>

      <Field label={i18n.t('tree.scriptTemplateForms.seersHut.requirement')}>
        <EnumSelect
          value={requirementType}
          onChange={(v) => setField(setInput, 'requirementType', v)}
          options={REQUIREMENT_OPTIONS}
        />
      </Field>
      <RequirementFields {...props} />

      <Field label={i18n.t('story.storyBuilderDialog.kinds.reward')}>
        <EnumSelect
          value={rewardType}
          onChange={(v) => setField(setInput, 'rewardType', v)}
          options={REWARD_OPTIONS}
        />
      </Field>
      <RewardFields {...props} />

      <Field label={i18n.t('story.storyBuilderDialog.tone')}>
        <EnumSelect
          value={toneOf(input)}
          onChange={(v) => setField(setInput, 'tone', v)}
          options={TONES.map((t) => ({ id: t, label: toneLabel(t) }))}
        />
      </Field>

      <div className="space-y-2 rounded-md border border-border p-3">
        <div className="flex items-center justify-between">
          <p className="text-xs font-medium">{i18n.t('tree.scriptTemplateForms.questGiver.generatedTextPreview')}</p>
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={() => setField(setInput, 'seed', String(1 + Math.floor(Math.random() * 999_999)))}
          >
            <RefreshCw className="mr-1 h-3 w-3" /> {i18n.t('tree.scriptTemplateForms.questGiver.reRoll')}
          </Button>
        </div>
        <PreviewLine label={i18n.t('mapGrid.mapGameSettingsDialog.title')} value={text.title} />
        <PreviewLine label={i18n.t('mapGrid.mapGameSettingsDialog.description')} value={text.desc} />
        <PreviewLine label={i18n.t('tree.scriptTemplateForms.questGiver.onFirstVisit')} value={text.intro} />
        <PreviewLine label={i18n.t('tree.scriptTemplateForms.questGiver.onReward')} value={text.success} />
        <p className="text-xs text-muted-foreground">
          {i18n.t('tree.scriptTemplateForms.questGiver.theTextIsSavedAs')}
        </p>
      </div>
    </Fragment>
  )
}

function PreviewLine({ label, value }: { label: string; value: string }) {
  return (
    <p className="text-xs">
      <span className="text-muted-foreground">{label}: </span>
      {value}
    </p>
  )
}

function validate(input: ScriptTemplateInput): string[] {
  const errors: string[] = []
  if (!field(input, 'giverSid').trim()) errors.push(i18n.t('tree.scriptTemplateForms.errors.giver'))
  return [...errors, ...validateRequirementAndReward(input)]
}

function generate(
  input: ScriptTemplateInput,
  existingSids: { quests: string[]; dialogs: string[] },
) {
  const giverSid = field(input, 'giverSid').trim()
  const text = generateQuestText(toneOf(input), describeParts(input), seedOf(input))
  const { condition, consume } = buildRequirement(input)
  const rewardAction = buildReward(input)

  const questSid = existingSids.quests.includes(BASE_QUEST_SID)
    ? uniqueSid(BASE_QUEST_SID, existingSids.quests)
    : BASE_QUEST_SID

  const introDialogSid = `${questSid}_intro`
  const successDialogSid = `${questSid}_success`
  const nameSid = `${questSid}_name`
  const descSid = `${questSid}_desc`
  const introTextSid = `${introDialogSid}_text`
  const successTextSid = `${successDialogSid}_text`

  const localizationTokens: Record<string, string> = {
    [nameSid]: text.title,
    [descSid]: text.desc,
    [introTextSid]: text.intro,
    [successTextSid]: text.success,
  }

  const flow = (id: string, textSid: string): DialogFlow => ({
    id,
    slides: [{ id: 'main', text: textSid, end: true }],
  })
  const dialogFlows = [
    flow(introDialogSid, introTextSid),
    flow(successDialogSid, successTextSid),
  ]

  const triggers: Trigger[] = [
    {
      conditions: [{ c: 'ObjectInteractionAfter', p: [giverSid, ''] }],
      actions: [{ a: 'Dialog', p: [introDialogSid] }],
    },
    {
      conditionsLogic: 'And',
      conditions: [{ c: 'ObjectInteractionAfter', p: [giverSid, ''] }, condition],
      actions: [
        ...consume,
        rewardAction,
        { a: 'Dialog', p: [successDialogSid] } as Action,
        { a: 'CurrentSubQuestDone', p: [] } as Action,
      ],
    },
  ]

  const subQuest: SubQuest = { sid: '1', activeOnStart: true, comment: GENERATED_COMMENT, triggers }

  const quest: Quest = {
    sid: questSid,
    name: nameSid,
    desc: descSid,
    activeOnStart: true,
    comment: GENERATED_COMMENT,
    subQuests: [subQuest],
  }

  return { quest, dialogFlows, localizationTokens }
}

export const questGiverTemplate: ScriptTemplateDef = {
  id: 'quest-giver',
  name: 'Quest Giver (generated text)',
  description:
    'A visible quest handed out at an object, with the quest log title, description and the intro/reward dialogs written for you in a tone you pick (heroic, grim, humorous, mysterious). Re-roll until you like the wording; edit it later in the Localization editor.',
  category: 'Quest Generator',
  slots: [],
  renderFields,
  validate: (input) => validate(input),
  generate: (input, _mapContext, existingSids) => generate(input, existingSids),
}
